export default function Services({ 
  searchQuery = '',
  onSelectService
}: { 
  searchQuery?: string;
  onSelectService?: (serviceTitle: string) => void;
}) {
  const [selectedService, setSelectedService] = useState<{ category: string; service: ServiceItem } | null>(null);

  const colors = [
    "from-[#46EB2D] to-[#3cc426] border-[#46EB2D]",
    "from-[#0FD1DC] to-[#0cb8c2] border-[#0FD1DC]",
    "from-[#E21841] to-[#c21438] border-[#E21841]",
    "from-[#DCE318] to-[#c7cd15] border-[#DCE318]"
  ];

  const filteredCategories = Object.entries(groupedServices).map(([category, items]) => {
    const filteredItems = items.filter(service => 
      service.title.toLowerCase().includes(searchQuery.toLowerCase()) || 
      service.desc.toLowerCase().includes(searchQuery.toLowerCase()) ||
      category.toLowerCase().includes(searchQuery.toLowerCase())
    );
    return [category, filteredItems] as [string, typeof items];
  }).filter(([_, items]) => items.length > 0);

  const handleBookService = () => {
    if (selectedService && onSelectService) {
      onSelectService(selectedService.service.title);
    }
    setSelectedService(null);
    const contactElem = document.getElementById('contact');
    if (contactElem) {
      contactElem.scrollIntoView({ behavior: 'smooth' });
    }
  };

  return (
    <section id="services" className="py-10 bg-white relative">
      <div className="max-w-7xl mx-auto px-4">
        {filteredCategories.length === 0 ? (
          <div className="text-center py-12 text-slate-500 text-sm">
            কোনো সার্ভিস পাওয়া যায়নি &quot;{searchQuery}&quot; এর জন্য।
          </div>
        ) : (
          filteredCategories.map(([category, items], catIndex) => (
            <div key={category} className="mb-8">
              <h2 className="text-lg font-bold text-slate-900 mb-4 border-l-4 border-blue-600 pl-3">{category}</h2>
              <div className="grid grid-cols-2 gap-3">
                {items.map((service, i) => {
                  const colorClass = colors[(catIndex * 3 + i) % colors.length];
                  return (
                    <div key={service.title} className="bg-white p-0.5 rounded-2xl border border-slate-200 shadow-sm transition hover:shadow-md flex flex-col justify-between">
                      <div className={`bg-gradient-to-br ${colorClass} p-3 rounded-[14px] mb-0.5 flex flex-col items-center text-center text-white`}>
                        <div className="text-2xl mb-1">{service.icon}</div>
                        <h3 className="text-[11px] font-bold leading-tight">{service.title}</h3>
                      </div>
                      <div className="p-2 text-center flex flex-col justify-between flex-grow">
                        <p className="text-slate-600 text-[9px] leading-tight mb-2 line-clamp-2">{service.desc}</p>
                        {/* 'বিস্তারিত' button opens full in-app details modal */}
                        <button
                          type="button"
                          onClick={() => setSelectedService({ category, service })}
                          className="w-full inline-block bg-slate-100 hover:bg-blue-50 hover:text-blue-600 text-slate-800 font-bold py-1.5 rounded-lg text-[10px] transition cursor-pointer border border-slate-200"
                        >
                          বিস্তারিত
                        </button>
                      </div>
                    </div>
                  );
                })}
              </div>
            </div>
          ))
        )}
      </div>

      {/* Service Details In-App Modal (Shows detailed info within the app) */}
      <AnimatePresence>
        {selectedService && (
          <div className="fixed inset-0 z-50 flex items-center justify-center p-4 sm:p-6 bg-slate-900/60 backdrop-blur-xs">
            <motion.div
              initial={{ opacity: 0, scale: 0.95, y: 15 }}
              animate={{ opacity: 1, scale: 1, y: 0 }}
              exit={{ opacity: 0, scale: 0.95, y: 15 }}
              transition={{ duration: 0.2 }}
              className="bg-white rounded-3xl max-w-lg w-full max-h-[90vh] overflow-y-auto p-6 sm:p-8 border border-slate-200 shadow-2xl relative"
            >
              {/* Close Button */}
              <button
                type="button"
                onClick={() => setSelectedService(null)}
                className="absolute top-5 right-5 p-2 rounded-full bg-slate-100 hover:bg-slate-200 text-slate-600 hover:text-slate-900 transition cursor-pointer"
                aria-label="বন্ধ করুন"
              >
                <X size={18} />
              </button>

              {/* Header */}
              <div className="flex items-center gap-3.5 mb-5 pr-8">
                <div className="w-14 h-14 rounded-2xl bg-blue-50 border border-blue-100 flex items-center justify-center text-3xl shrink-0">
                  {selectedService.service.icon}
                </div>
                <div>
                  <span className="text-[11px] font-bold text-blue-600 uppercase tracking-wider bg-blue-50 px-2.5 py-0.5 rounded-md border border-blue-100">
                    {selectedService.category}
                  </span>
                  <h3 className="text-xl font-extrabold text-slate-900 mt-1 leading-snug">
                    {selectedService.service.title}
                  </h3>
                </div>
              </div>

              {/* Main Description */}
              <div className="mb-5 bg-slate-50 p-4 rounded-2xl border border-slate-100">
                <h4 className="text-xs font-bold text-slate-500 uppercase tracking-wide mb-1">কাজের পরিসর ও উদ্দেশ্য</h4>
                <p className="text-slate-700 text-sm leading-relaxed font-medium">
                  {selectedService.service.scope || selectedService.service.desc}
                </p>
              </div>

              {/* Included Features */}
              <div className="mb-6">
                <h4 className="text-xs font-bold text-slate-900 uppercase tracking-wide mb-3 flex items-center gap-1.5">
                  <Sparkle size={14} className="text-amber-500" /> এই সেবায় যা যা অন্তর্ভুক্ত রয়েছে:
                </h4>
                <ul className="space-y-2.5">
                  {(selectedService.service.features || [
                    '১০০% প্রফেশনাল মান নিশ্চিতকরণ',
                    'নিরাপদ ও নির্ভরযোগ্য কাজ',
                    'প্রয়োজনে ফ্রি রিভিশন সুবিধা',
                    '২৪/৭ ডেডিকেটেড সাপোর্ট'
                  ]).map((feat, idx) => (
                    <li key={idx} className="flex items-start gap-2.5 text-xs text-slate-700 font-medium">
                      <CheckCircle2 size={16} className="text-emerald-500 shrink-0 mt-0.5" />
                      <span>{feat}</span>
                    </li>
                  ))}
                </ul>
              </div>

              {/* Delivery info */}
              <div className="flex items-center justify-between p-3.5 bg-blue-50/60 rounded-xl border border-blue-100 mb-6">
                <div className="flex items-center gap-2 text-xs text-slate-700 font-bold">
                  <Clock size={16} className="text-blue-600" />
                  <span>আনুমানিক ডেলিভারি সময়:</span>
                </div>
                <span className="text-xs font-extrabold text-blue-700">
                  {selectedService.service.delivery || 'দ্রুত সময়ের মধ্যে'}
                </span>
              </div>

              {/* Action Buttons */}
              <div className="flex gap-3">
                <button
                  type="button"
                  onClick={() => setSelectedService(null)}
                  className="flex-1 py-3 px-4 rounded-xl border border-slate-200 text-slate-700 font-bold text-xs hover:bg-slate-50 transition cursor-pointer"
                >
                  বন্ধ করুন
                </button>
                <button
                  type="button"
                  onClick={handleBookService}
                  className="flex-1 py-3 px-4 rounded-xl bg-blue-600 hover:bg-blue-700 text-white font-bold text-xs shadow-md shadow-blue-500/20 transition flex items-center justify-center gap-1.5 cursor-pointer"
                >
                  <span>সেবাটি বুক করুন</span>
                  <ArrowRight size={14} />
                </button>
              </div>
            </motion.div>
          </div>
        )}
      </AnimatePresence>
    </section>
  );
}
